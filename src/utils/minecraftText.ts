const SHADOW_OFFSET = 2
// Последние 2 пикселя advance — промежуток до следующего символа, в ширину текста они не входят
const GAP = 2

export const minecraftTextWidth = (text: string): number =>
  [...text].reduce((width, char) => width + (GLYPHS[char]?.advance ?? 12), 0) - GAP

const gray = (level: number): string => `rgb(${level}, ${level}, ${level})`

// Рисует текст с тенью, x и y — левый верхний угол самого текста (без тени)
export function drawMinecraftText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number): void {
  // Как в игре: сначала тень всей строки, потом сам текст поверх
  for (const layer of ['shadow', 'text'] as const) {
    const offset = layer === 'shadow' ? SHADOW_OFFSET : 0
    let left = x
    for (const char of text) {
      const glyph = GLYPHS[char]
      if (glyph) {
        const colors = glyph[layer]
        glyph.rows.forEach((row, rowIndex) => {
          const level = colors[rowIndex + offset] ?? colors[colors.length - 1]
          ctx.fillStyle = gray(level)
          for (let col = 0; col < row.length; col++) {
            if (row[col] === '#') ctx.fillRect(left + col + offset, y + rowIndex + offset, 1, 1)
          }
        })
      }
      left += glyph?.advance ?? 12
    }
  }
}
